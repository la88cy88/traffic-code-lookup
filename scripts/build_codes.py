def norm(s):
    return re.sub(r'[^0-9A-Za-z\u4e00-\u9fff]', '', str(s or ''))


def add_aliases(recs):
    for r in recs:
        aliases = list(r.get('alias') or [])
        for kw, words in ALIAS_RULES:
            if norm(kw) in norm(r['behavior']):
                for w in words:
                    if w not in aliases:
                        aliases.append(w)
        r['alias'] = aliases[:4]


def main():
    gd = json.load(open(os.path.join(DATA, 'guangdong.json'), encoding='utf-8'))
    cn = json.load(open(os.path.join(DATA, 'national.json'), encoding='utf-8'))
    gd_rows, cn_rows = gd['codes'], cn['codes']

    for r in gd_rows:
        r['source'] = 'GD'
        r['sourceLabel'] = GD_SOURCE['label']
        r['id'] = r['code']
        r.setdefault('note', '')
        r.setdefault('localRef', False)
    for r in cn_rows:
        r['source'] = 'CN'
        r['sourceLabel'] = CN_SOURCE['label']
        r['id'] = r['code']
        r.setdefault('extra', [])
    gd_codes = {r['code'] for r in gd_rows}
    for r in cn_rows:
        if r['code'] in gd_codes:
            r['id'] = 'cn:' + r['code']
    # 修正广东表解析时误加的俗称（1902 实为未悬挂号牌，1007 是把车交给无证者）
    ALIAS_FIX = {'1902': ['未悬挂号牌'], '1007': ['把车借给无证的人']}
    for r in gd_rows:
        if r['code'] in ALIAS_FIX:
            r['alias'] = list(ALIAS_FIX[r['code']])
    add_aliases(gd_rows)
    add_aliases(cn_rows)

    all_rows = gd_rows + cn_rows
    by_key = {}
    for r in all_rows:
        by_key.setdefault(norm(r['behavior']), []).append(r)
    # 行为表述完全一致的自动互链
    for group in by_key.values():
        ids = [r['id'] for r in group]
        for r in group:
            r['cross'] = [x for x in ids if x != r['id']][:3]
    by_code = {r['code']: r for r in all_rows}
    for a, b in CROSS_PAIRS:
        ra, rb = by_code.get(a), by_code.get(b)
        if not ra or not rb:
            continue
        for x, y in ((ra, rb), (rb, ra)):
            cross = x.setdefault('cross', [])
            if y['id'] not in cross:
                cross.append(y['id'])
    for r in all_rows:
        r.setdefault('cross', [])

    GD_SOURCE['count'] = len(gd_rows)
    CN_SOURCE['count'] = len(cn_rows) - 0  # 全国通用条目数（已剔除 7 字头地方码）
    meta = {
        'source': '广东 2022 + 全国通用 2022（两套公示代码表）',
        'version': '2022 年版公示文本 · 合并于 ' + date.today().isoformat(),
        'note': '参考信息，需自行核查现行版本、本地代码与罚款标准；两套代码新旧并存，不作为可直接录入的结论。',
        'count': len(all_rows),
        'sources': [GD_SOURCE, CN_SOURCE],
        'synonyms': SYNONYMS,
        'quick': QUICK,
        'hot': HOT,
        'disclaimer': '代码可查，结论仍需自行核查：新旧代码并存、地方罚款幅度不同，本页不提供可直接录入的代码结论。',
    }
    payload = {'meta': meta, 'codes': all_rows}
    with open(os.path.join(DATA, 'codes.json'), 'w', encoding='utf-8') as f:
        json.dump(payload, f, ensure_ascii=False, indent=1)
    with open(os.path.join(DATA, 'codes.js'), 'w', encoding='utf-8') as f:
        f.write('/* 自动生成，请勿手工编辑；见 scripts/build_codes.py */\n')
        f.write('window.CODE_DATA = ' + json.dumps(payload, ensure_ascii=False, separators=(',', ':')) + ';\n')

    missing_hot = [c for c in HOT if c not in by_code]
    bad_syn = [q for g in QUICK for q in [i['q'] for i in g['items']] if q not in SYNONYMS and norm(q) not in SYNONYMS]
    print('合并完成：广东', len(gd_rows), '+ 全国通用', len(cn_rows), '=', len(all_rows), '条')
    print('全国通用中引用地方实施办法', sum(1 for r in cn_rows if r['localRef']), '条')
    print('缺失常用代码', missing_hot)
    print('快捷词缺少同义词映射', bad_syn)
    for q in ['超员', '货物超载', '运沙石', '摩托车未戴头盔', '后排未系安全带', '闯红灯',
              '酒驾', '无证驾驶', '违停', '超速', '打电话', '遮挡号牌', '未年检', '应急车道']:
        words = SYNONYMS.get(q, [])
        hits = [r for r in all_rows if any(norm(w) in norm(r['behavior']) for w in words)]
        print(' ', q, len(hits), '例', (hits[0]['source'] + ' ' + hits[0]['code']) if hits else 'MISSING')


if __name__ == '__main__':
    main()
